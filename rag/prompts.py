# ==================== 会话摘要（长期记忆压缩）====================

# 为什么摘要要单独设计一个 Prompt？
# 因为摘要的目标不是"记录"，而是"保留对话中对后续问答有用的信息"。
# 如果只是笼统地写"请总结这段对话"，模型会写出"用户问了退货问题，
# 客服做了回答"这种毫无信息量的废话——下次用户问"那我要付运费吗"，
# 这份摘要在任何帮助都没有。
# 所以必须明确要求它保留【事实性信息】：订单号、商品名、具体政策、用户诉求。
SUMMARY_PROMPT = """请把下面这段客服对话压缩成一段简短的摘要。

要求：
1. 保留对后续对话有用的事实信息：用户提到的具体商品、订单号、时间、金额，
   以及已经确认过的结论（比如"已确认该商品不支持退货"）。
2. 不要保留寒暄、客套话和重复内容。
3. 用第三人称陈述，直接写事实，不要写"这段对话主要讲了……"这类废话。
4. 如果摘要里已有旧内容，请把新内容【合并】进去，形成一份完整的新摘要，
   不要出现"之前提到过……现在又提到……"这种层层套娃的写法。
5. 控制在 300 字以内。

{previous_summary}

以下是需要压缩的新对话：
{new_conversation}

压缩后的摘要："""


# 注册表：版本号 → 模板。上层只认版本号，不认具体内容
PROMPT_REGISTRY: dict[str, PromptTemplate] = {
    "v1": PROMPT_V1,
    "v2": PROMPT_V2,
    "v3": PROMPT_V3,
    "v4": PROMPT_V4,
}

# 默认版本。改 core/config.py 里的 PROMPT_VERSION 可以全局切换
DEFAULT_PROMPT_VERSION = "v2"


def get_prompt(version: str | None = None) -> PromptTemplate:
    """按版本号取模板，取不到就回退到默认版本。

    ★ 为什么是"回退"而不是"抛异常"？
      因为版本号可能来自配置文件或环境变量。线上服务不该因为
      配置里写错一个字母就整个 500。回退 + 告警日志是更稳的做法。
    """
    import logging

    logger = logging.getLogger(__name__)
    version = (version or DEFAULT_PROMPT_VERSION).strip()

    if version not in PROMPT_REGISTRY:
        logger.warning(
            "未知的 Prompt 版本 %r，已回退到 %s。可用版本：%s",
            version,
            DEFAULT_PROMPT_VERSION,
            ", ".join(sorted(PROMPT_REGISTRY)),
        )
        version = DEFAULT_PROMPT_VERSION

    return PROMPT_REGISTRY[version]


def list_prompt_versions() -> list[dict]:
    """列出所有版本及其说明。接口暴露出来，方便在 Swagger 里直接看。"""
    return [
        {
            "version": p.version,
            "note": p.note,
            "temperature": p.temperature,
            "is_default": p.version == DEFAULT_PROMPT_VERSION,
        }
        for p in PROMPT_REGISTRY.values()
    ]
