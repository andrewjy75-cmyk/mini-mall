"""Prompt 工程：所有提示词集中在这里，并做版本管理。

为什么 Prompt 要单独一个文件、还要带版本号？

刚上手时大家习惯把提示词直接写在业务函数里。但只要开始调优就会立刻失控：
改了三个字，效果变好了——好在哪？不知道。想回退到上一版？没存。
想做 A/B 对比？两个版本混在一个函数里，只能靠注释来回切。

所以这里的做法是：
1. 每个版本是一个独立、完整、可回退的模板
2. 每个版本都标注"改了什么、为什么这么改、预期改善哪一类问题"
3. 版本号会被写进每条回答的埋点（ChatMessage.prompt_version），
   让"效果提升"这件事可以被数据验证，而不是凭感觉说

★ 关于幻觉，先讲清楚一个反直觉的事实：
   给模型加一句"不要编造"，效果非常有限。真正管用的是三件事——
   (1) 给它一个体面的"我不知道"出口。模型编造，很多时候是因为它以为
       "答不上来"等于"任务失败"，于是硬凑一个答案。
   (2) 要求它引用来源。一旦必须给出处，凭空编造的成本就变高了。
   (3) 把资料编号给它，允许它说"资料 2 和 3 有冲突"。
   这三条正是 v2 相对 v1 的核心改动，对比数据在 docs 的优化文档里。
"""

from typing import NamedTuple


class PromptTemplate(NamedTuple):
    """一套提示词模板。

    system: 定角色和铁律（模型的"人设"和底线）
    human:  每轮变化的部分（资料 + 问题）
    note:   这一版的改动说明，写给自己和评审看
    """

    version: str
    system: str
    human: str
    note: str
    temperature: float = 0.1


# 所有版本共用的"资料拼接格式"。
# 用【资料 N】而不是纯文本堆叠，是为了让模型能可靠地引用编号——
# 编号是引用溯源的基础设施，乱不得。
CONTEXT_HEADER = "以下是知识库检索到的资料："


def build_context_block(items: list[tuple[str, str]]) -> str:
    """把检索结果拼成给模型看的资料块。

    参数:
        items: [(标题, 正文), ...]，顺序即编号顺序

    返回形如：
        【资料 1】《退换货政策》
        商品签收后 7 天内可无理由退货...
        ---
        【资料 2】...

    ★ 带上《标题》很关键。同一批资料里可能有互相矛盾的条款
      （通用政策和特殊商品说明），标注出处能让模型自己发现冲突并说明，
      而不是把两个矛盾的答案糅成一段话——那是最难排查的一类幻觉。
    """
    if not items:
        return "（本次没有检索到相关资料）"

    blocks: list[str] = []
    for index, (title, content) in enumerate(items, start=1):
        header = f"【资料 {index}】" + (f"《{title}》" if title else "")
        blocks.append(f"{header}\n{content.strip()}")
    return "\n---\n".join(blocks)


