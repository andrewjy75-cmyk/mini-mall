def cases_by_category(category: str) -> list[EvalCase]:
    return [c for c in EVAL_CASES if c.category == category]


def summary() -> dict:
    """评估集概况，跑评估前先打印出来。"""
    return {
        "total": len(EVAL_CASES),
        "answerable": len(cases_by_category("answerable")),
        "unanswerable": len(cases_by_category("unanswerable")),
        "trap": len(cases_by_category("trap")),
    }
