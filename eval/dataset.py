"""幻觉调优评估集。

★ 这份评估集是整个"优化文档"的地基。没有它，所谓"优化后效果变好了"
  就只是自我感觉；有了它，才能写出「v1 在 6 道不可回答题上全部编造答案，
  v2 拒答率 100%」这样可以被复核的结论。

设计上分三类，每类的考察目标完全不同：

  A. 可回答（13 题）
     答案明确写在文档里。考的是【检索准不准 + 答得对不对】。
     其中特意放了几道需要跨文档综合的题（见 q11），
     单靠一次向量检索很容易只召回到一半信息，正好用来验证重排的价值。

  B. 不可回答（6 题）★ 这是衡量幻觉的核心
     文档里【根本没有】这个信息。模型只有两种表现：
         正确：明确说「没查到」        → 好
         错误：编一个听起来合理的答案  → 幻觉
     这类题最能拉开版本差距。因为可回答的题，模型靠自己学过的知识
     也可能蒙对；但不可回答的题只要它敢给具体信息，就一定是在编。
     所以评估幻觉率时，这一类的数据比前一类有说服力得多。

  C. 陷阱题（3 题）
     文档里有答案，但旁边紧挨着一个容易混淆的限定条件。
     比如「金卡会员退货延长到 15 天」后面紧跟一句
     「该权益仅适用于原本支持无理由退货的普通商品」。
     模型如果只抓到前半句，就会答出「生鲜也能退 15 天」这种
     有出处、但结论错误的答案——这是最难被发现的一类幻觉。

★ key_points 的作用：
  用 LLM 当裁判判定对错时，不能只丢一个「参考答案」给裁判（太宽松），
  要把答案拆成必须覆盖的要点，让裁判逐个核对，判定才稳定、可复现。

★ 注意本文件注释里统一用「」而不是英文引号：
  因为注释和字符串里到处都是引号，混用很容易把字符串提前截断。
  这类语法错误虽然低级，但排查起来很费时间，不如一开始就规避。
"""

from dataclasses import dataclass


@dataclass
class EvalCase:
    """一道评估题。"""

    id: str
    question: str
    category: str            # answerable / unanswerable / trap
    answerable: bool
    key_points: list[str]    # 必须命中的要点（不可回答的题为空）
    note: str = ""           # 这道题想考察什么

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "question": self.question,
            "category": self.category,
            "answerable": self.answerable,
            "key_points": self.key_points,
            "note": self.note,
        }


